CREATE TABLE IF NOT EXISTS USUARIO (
    ID_USUARIO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(120) NOT NULL,
    EMAIL VARCHAR(160) NOT NULL UNIQUE,
    SENHA_HASH VARCHAR(255) NOT NULL,
    PERFIL VARCHAR(10) DEFAULT 'USUARIO' NOT NULL,
    DATA_CADASTRO DATE NOT NULL,
    ATIVO BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS FILME (
    ID_FILME INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO VARCHAR(200) NOT NULL,
    SINOPSE VARCHAR(2000),
    ANO INT NOT NULL,
    DURACAO INT NOT NULL,
    POSTER_URL VARCHAR(500),
    ATIVO BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS GENERO (
    ID_GENERO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(60) NOT NULL UNIQUE,
    DESCRICAO VARCHAR(255),
    ORDEM INT,
    ATIVO BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE IF NOT EXISTS FILME_GENERO (
    ID_FILME INT NOT NULL,
    ID_GENERO INT NOT NULL,
    PRIMARY KEY (ID_FILME, ID_GENERO),
    FOREIGN KEY (ID_FILME) REFERENCES FILME(ID_FILME),
    FOREIGN KEY (ID_GENERO) REFERENCES GENERO(ID_GENERO)
);

CREATE TABLE IF NOT EXISTS REGISTRO_PESSOAL (
    ID_USUARIO INT NOT NULL,
    ID_FILME INT NOT NULL,
    STATUS VARCHAR(15) NOT NULL,
    FAVORITO BOOLEAN DEFAULT FALSE NOT NULL,
    NOTA DECIMAL(2,1),
    DATA_REGISTRO DATE,
    PRIMARY KEY (ID_USUARIO, ID_FILME),
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    FOREIGN KEY (ID_FILME) REFERENCES FILME(ID_FILME)
);

CREATE TABLE IF NOT EXISTS RESENHA (
    ID_RESENHA INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    ID_FILME INT NOT NULL,
    TEXTO VARCHAR(2000) NOT NULL,
    DATA_PUBLICACAO DATE NOT NULL,
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    FOREIGN KEY (ID_FILME) REFERENCES FILME(ID_FILME)
);
